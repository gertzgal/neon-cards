/** Strips spaces so each row can be read in groups of four. */
export function grid(art: string): string[] {
  const lines = art
    .replace(/^\n/, '')
    .replace(/\n\s*$/, '')
    .split('\n')
    .map((line) => line.replace(/ /g, ''))
    .filter((line) => line.length > 0)
  const width = lines[0]?.length ?? 0
  if (width < 8) throw new Error('scene is too narrow')
  for (const line of lines) {
    if (line.length !== width) throw new Error(`scene width ${line.length} != ${width}: ${line}`)
  }
  return lines
}

